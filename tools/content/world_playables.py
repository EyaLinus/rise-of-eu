def check_keys():
    """Every province and realm named by the missions and events must exist."""
    mp = json.load(open(os.path.join(ROOT, "data/map.json"), encoding="utf-8"))
    keys = {p["key"] for p in mp["provinces"]}
    tags = set(json.load(open(os.path.join(ROOT, "data/nations.json"), encoding="utf-8")))
    bad = []
    for tag, ms in MISSIONS.items():
        for x in ms:
            for k in ("owns", "owns_any"):
                bad += [(x["id"], p) for p in x["require"].get(k, []) if p not in keys]
            if "allied" in x["require"] and x["require"]["allied"] not in tags:
                bad.append((x["id"], x["require"]["allied"]))
    for e in EVENTS:
        assert e["tag"] in PLAYABLE, e["id"]
        for k in ("owns", "not_owns"):
            bad += [(e["id"], p) for p in e["trigger"].get(k, []) if p not in keys]
        if "alive" in e["trigger"] and e["trigger"]["alive"] not in tags:
            bad.append((e["id"], e["trigger"]["alive"]))
        for o in e["options"]:
            fx = o["effects"]
            bad += [(e["id"], p) for p in fx.get("claim", []) if p not in keys]
            bad += [(e["id"], t) for t in fx.get("relations", {}) if t not in tags]
            if "war" in fx and fx["war"] not in tags:
                bad.append((e["id"], fx["war"]))
    for tag, cl in CLAIMS.items():
        bad += [(tag, p) for p in cl if p not in keys]
    assert not bad, bad


def main():
    check_keys()
    # nations: playable flag + player bonus (one line per nation, keep the layout)
    path = os.path.join(ROOT, "data/nations.json")
    lines = open(path, encoding="utf-8").read().split("\n")
    for i, l in enumerate(lines):
        mt = re.match(r'  "([A-Z]{3})": ', l)
        if not mt or mt.group(1) not in PLAYABLE:
            continue
        tag = mt.group(1)
        if '"playable": true' not in l:
            l = l.replace('"emoji": ', '"playable": true, "emoji": ', 1)
            assert '"playable": true' in l, tag
        if tag in PLAYER_BONUS and '"player_bonus"' not in l:
            idea, bonus = PLAYER_BONUS[tag]
            assert l.rstrip().endswith("},") or l.rstrip().endswith("}"), tag
            end = l.rstrip()
            comma = end.endswith(",")
            body = end[:-1] if comma else end
            body = body[:-1] + ', "player_bonus": %s, "player_idea": %s}' % (json.dumps(bonus), json.dumps(idea, ensure_ascii=False))
            l = body + ("," if comma else "")
        lines[i] = l
    out = "\n".join(lines)
    nd = json.loads(out)
    for t in PLAYABLE:
        assert nd[t].get("playable"), t
    open(path, "w", encoding="utf-8").write(out)
    # start claims
    path = os.path.join(ROOT, "data/diplomacy.json")
    dip = json.load(open(path, encoding="utf-8"))
    for tag, cl in CLAIMS.items():
        dip["claims"][tag] = cl
    with open(path, "w", encoding="utf-8") as f:
        json.dump(dip, f, ensure_ascii=False, indent=2)
        f.write("\n")
    # missions: national block before rivalry/era missions
    path = os.path.join(ROOT, "data/missions.json")
    data = json.load(open(path, encoding="utf-8"))
    for tag in PLAYABLE:
        old = [x for x in data.get(tag, []) if "_np_" not in x["id"]]
        keep = [x for x in old if "_riv_" not in x["id"]]
        riv = [x for x in old if "_riv_" in x["id"]]
        data[tag] = keep + MISSIONS[tag] + riv
    ids = [x["id"] for v in data.values() for x in v]
    assert len(ids) == len(set(ids))
    out = "{\n" + ",\n".join('  "%s": [\n' % tag + ",\n".join(render_mission(x) for x in ms) + "\n  ]" for tag, ms in data.items()) + "\n}\n"
    json.loads(out)
    open(path, "w", encoding="utf-8").write(out)
    replace_block("np2_", EVENTS)
    per = {t: sum(1 for e in EVENTS if e["tag"] == t) for t in PLAYABLE}
    print("playable", PLAYABLE, "missions", {t: len(data[t]) for t in PLAYABLE}, "events", per)


if __name__ == "__main__":
    main()
