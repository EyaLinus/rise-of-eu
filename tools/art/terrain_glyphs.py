"""Small terrain sprites for the world map (map_view._draw_terrain_glyphs): woods, dunes, oasis palm,
reeds and hills, drawn over the political colours so the land reads as a landscape at a glance.
Writes assets/src/pixel/icons/terr_*.txt; tools/build_art.sh renders them x2 into assets/art/icons."""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from pixlib import blank, layer, paste, write

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "assets", "src", "pixel", "icons")

# woods: two round trees and a small one, 16x12 with outline
forest = layer([
    "...l......l...",
    "..lLL....lLL..",
    ".lLLLF..lLLLF.",
    ".LLLLF..LLLLF.",
    "..LLF.l..LLF..",
    "...H.lLL..H...",
    "...H.LLLF.H...",
    "......LLF.....",
    ".......H......",
], 1, 1, 16, 11)

# dunes: two sand crests with their shadow side, no outline (soft), 16x6
dunes = paste(blank(16, 6), [
    "......YG........",
    "....YYYGG.......",
    "..YYYYYGGG...YG.",
    ".YYYYYYGGGGYYYGG",
    "YYYYYYGGGGGGGGGD",
    "..DDDDDDD..DDDD.",
])

# oasis: a date palm over a dune, 12x10 (developed desert provinces)
oasis = layer([
    ".LLL.LLL..",
    "L..LLH..L.",
    "....OL....",
    "....O.....",
    "...O......",
    "...O..YY..",
    "..YOYYYYG.",
    "YYYYYYYGGG",
], 1, 1, 12, 10)

# marsh: reeds standing in water, 12x7
marsh = paste(blank(12, 7), [
    "..H....H....",
    "..L.L..L.L..",
    "..L.L.LL.L..",
    ".LL.L.L..LL.",
    "bBBbBBBbBBb.",
    ".BBbBBBbBB..",
    "...NNN.NN...",
])

# hills: two rounded humps with a shaded flank, 16x7 with outline
hills = layer([
    "....PP........",
    "...PPPQ..PP...",
    "..PPPPQQPPPQ..",
    ".PPPPPQQPPPQQ.",
    "PPPPPPQQQPPPQQ",
], 1, 1, 16, 7)

if __name__ == "__main__":
    for key, g, what in (("terr_forest", forest, "woods"), ("terr_dunes", dunes, "sand dunes"), ("terr_oasis", oasis, "oasis palm"),
                         ("terr_marsh", marsh, "reeds in water"), ("terr_hills", hills, "rolling hills")):
        write(os.path.join(OUT, key + ".txt"), g, "%s – %s on the world map, %dx%d grid, export x2. Generated by tools/art/terrain_glyphs.py" % (key, what, len(g[0]), len(g)))
    print("terr_forest terr_dunes terr_oasis terr_marsh terr_hills")
