"""Small terrain sprites for the world map (map_view._draw_terrain_glyphs): woods, dunes, oasis palm,
reeds and hills, drawn over the political colours so the land reads as a landscape at a glance.
Writes assets/src/pixel/icons/terr_*.txt; tools/build_art.sh renders them x2 into assets/art/icons."""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from pixlib import blank, layer, paste, stack, write

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "assets", "src", "pixel", "icons")

# woods: two round trees and a small one, 16x12 with outline
forest = layer([
    "...l......l...",
    "..lLL....lLL..",
    ".lLLLF..lLLLF.",
    ".LLLLF..LLLLF.",
    "..LLF.l..LLF..",
    "...H.lLL..H...",
    "...H.LLLF.H...",
    "......LLF.....",
    ".......H......",
], 1, 1, 16, 11)

# dunes: two sand crests with their shadow side, no outline (soft), 16x6
dunes = paste(blank(16, 6), [
    "......YG........",
    "....YYYGG.......",
    "..YYYYYGGG...YG.",
    ".YYYYYYGGGGYYYGG",
    "YYYYYYGGGGGGGGGD",
    "..DDDDDDD..DDDD.",
])

# oasis: a date palm over a dune, 12x10 (developed desert provinces)
oasis = layer([
    ".LLL.LLL..",
    "L..LLH..L.",
    "....OL....",
    "....O.....",
    "...O......",
    "...O..YY..",
    "..YOYYYYG.",
    "YYYYYYYGGG",
], 1, 1, 12, 10)

# marsh: reeds standing in water, 12x7
marsh = paste(blank(12, 7), [
    "..H....H....",
    "..L.L..L.L..",
    "..L.L.LL.L..",
    ".LL.L.L..LL.",
    "bBBbBBBbBBb.",
    ".BBbBBBbBB..",
    "...NNN.NN...",
])

# hills: two rounded humps with a shaded flank, 16x7 with outline
hills = layer([
    "....PP........",
    "...PPPQ..PP...",
    "..PPPPQQPPPQ..",
    ".PPPPPQQPPPQQ.",
    "PPPPPPQQQPPPQQ",
], 1, 1, 16, 7)

# --- terrain badges (map_view._draw_badges): one 16x16 icon per terrain type, drawn next to the
# province's trade good on a small parchment plaque. Same grid as the pixel emoji (1 art px = 1 map px).

# plains: flat meadow with grass tufts (no wheat: grain is a trade good shown right next to it)
tico_plains = layer([
    ".............",
    "..l.......l..",
    ".lL.l..l..L.l",
    ".LL.L.lL.lL.L",
    "lLLlLLLlLLLl.",
    "LLLLLLLLLLLLF",
    "FLLLLLLLLLLFF",
    ".FFFFFFFFFFF.",
], 1, 5, 16, 16)

# forest: a fir and a round leaf tree
tico_forest = stack(
    layer([
        "....l....",
        "...lLF...",
        "..lLLF...",
        "...LF....",
        "..lLLF...",
        ".lLLLLF..",
        "..LLLF...",
        ".lLLLLF..",
        "lLLLLLLF.",
        "....H....",
        "....H....",
    ], 1, 2, 16, 16),
    layer([
        "..lll..",
        ".lLLLF.",
        "lLLLLLF",
        "lLLLLLF",
        ".LLLLF.",
        "..FHF..",
        "...H...",
        "...H...",
    ], 8, 5, 16, 16),
)

# hills: two grassy humps, the far one darker
tico_hills = stack(
    layer([
        "....LLL...",
        "..LLLLLLF.",
        ".LLLLLLLFF",
        "LLLLLLLLFF",
    ], 5, 5, 16, 16),
    layer([
        "...lll.....",
        ".llLLLLF...",
        "lLLLLLLLF..",
        "LLLLLLLLLF.",
        "LLLLLLLLLFF",
        "FFFFFFFFFFF",
    ], 1, 8, 16, 16),
)

# mountains: a grey peak with a snow cap and a smaller one behind
tico_mountains = stack(
    layer([
        "...w...",
        "..wwa..",
        ".agaad.",
        "aggggdd",
    ], 8, 5, 16, 16),
    layer([
        ".....w.....",
        "....wwa....",
        "...wwwaa...",
        "..aggwgdd..",
        ".agggggddd.",
        "aggggggdddd",
        "dddddddddd.",
    ], 1, 6, 16, 16),
)

# desert: a sand dune under a sun
tico_desert = stack(
    layer([
        ".YY.",
        "YGGD",
        "YGGD",
        ".DD.",
    ], 10, 2, 16, 16),
    layer([
        ".....YY.......",
        "...YYYYGG.....",
        ".YYYYYYGGGG...",
        "YYYYYYGGGGGGG.",
        "GGGGGGGGGGDDDD",
    ], 1, 8, 16, 16),
)

# marsh: reeds in shallow water
tico_marsh = stack(
    layer([
        "..H.......H..",
        "..H...H...H..",
        "..L.L.H.L.L..",
        ".LL.L.L.L.LL.",
        ".L..L.L.L..L.",
    ], 1, 3, 16, 16),
    layer([
        "bBBbBBBBbBBBb",
        "BBBNBBBNBBBNB",
        ".NNNNNNNNNNN.",
    ], 1, 8, 16, 16),
)

TICOS = {"plains": tico_plains, "forest": tico_forest, "hills": tico_hills, "mountains": tico_mountains,
         "desert": tico_desert, "marsh": tico_marsh}


if __name__ == "__main__":
    for key, g, what in (("terr_forest", forest, "woods"), ("terr_dunes", dunes, "sand dunes"), ("terr_oasis", oasis, "oasis palm"),
                         ("terr_marsh", marsh, "reeds in water"), ("terr_hills", hills, "rolling hills")):
        write(os.path.join(OUT, key + ".txt"), g, "%s – %s on the world map, %dx%d grid, export x2. Generated by tools/art/terrain_glyphs.py" % (key, what, len(g[0]), len(g)))
    for t, g in TICOS.items():
        write(os.path.join(OUT, "tico_%s.txt" % t), g, "tico_%s – terrain badge (%s) on the world map, 16x16 grid, export x2. Generated by tools/art/terrain_glyphs.py" % (t, t))
    print("terr_forest terr_dunes terr_oasis terr_marsh terr_hills + tico_" + " tico_".join(TICOS))
